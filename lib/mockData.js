// Helper keys
const STORAGE_KEYS = {
  TILES: "sonata_tiles_data",
  CATALOGUES: "sonata_catalogues_data",
  ENQUIRIES: "sonata_enquiries_data",
  SERIES: "sonata_series_data"
};

// Tiles CRUD
export const getStoredTiles = () => {
  if (typeof window === "undefined") return mockTiles;
  const stored = localStorage.getItem(STORAGE_KEYS.TILES);
  if (!stored) {
    localStorage.setItem(STORAGE_KEYS.TILES, JSON.stringify(mockTiles));
    return mockTiles;
  }
  return JSON.parse(stored);
};

export const saveTile = (tile) => {
  const current = getStoredTiles();
  let updated;
  if (tile.id) {
    updated = current.map(item => item.id === tile.id ? { ...item, ...tile } : item);
  } else {
    const newTile = {
      ...tile,
      id: "tile-" + Date.now(),
      created_at: new Date().toISOString()
    };
    updated = [newTile, ...current];
  }
  localStorage.setItem(STORAGE_KEYS.TILES, JSON.stringify(updated));
  return updated;
};

export const deleteTile = (id) => {
  const current = getStoredTiles();
  const updated = current.filter(item => item.id !== id);
  localStorage.setItem(STORAGE_KEYS.TILES, JSON.stringify(updated));
  return updated;
};

